// buildStars — SVG star rating
// ============================================================
function buildStars(rating) {
  const svg = (cls) => `<svg class="star ${cls}" viewBox="0 0 20 20" xmlns="http://www.w3.org/2000/svg"><path d="M10 1l2.39 4.84 5.34.78-3.86 3.76.91 5.32L10 13.27l-4.78 2.53.91-5.32L2.27 6.62l5.34-.78z"/></svg>`;
  let html = '';
  for (let i = 1; i <= 5; i++) {
    if (i <= Math.floor(rating))    html += svg('filled');
    else if (i - rating < 1)        html += svg('half');
    else                            html += svg('empty');
  }
  return html;
}

// ============================================================
// isLightColor — detect if hex is too light (needs border)
// ============================================================
function isLightColor(hex) {
  if (!hex || hex.length < 7) return false;
  const r = parseInt(hex.slice(1,3),16);
  const g = parseInt(hex.slice(3,5),16);
  const b = parseInt(hex.slice(5,7),16);
  return (0.299*r + 0.587*g + 0.114*b) > 200;
}

// ============================================================
// preloadProductImages — preloads all color images into browser
// cache so switching is INSTANT (no network delay)
// ============================================================
function preloadProductImages(product) {
  if (!product.colors || product.colors.length <= 1) return;
  product.colors.forEach(c => {
    if (c.image) {
      const img = new Image();
      img.src = c.image;
    }
  });
}

