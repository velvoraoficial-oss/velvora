function getProductsByCategory(category) {
  if (!category || category === 'all' || category === 'All') {
    return products;
  }
  return products.filter(p => 
    p.category.toLowerCase() === category.toLowerCase() ||
    p.subcategory.toLowerCase() === category.toLowerCase() ||
    p.tags.includes(category.toLowerCase())
  );
}

function getProductById(id) {
  return products.find(p => p.id === id) || null;
}

function searchProducts(query) {
  const q = query.toLowerCase();
  return products.filter(p =>
    p.name.toLowerCase().includes(q) ||
    p.description.toLowerCase().includes(q) ||
    p.category.toLowerCase().includes(q) ||
    p.subcategory.toLowerCase().includes(q) ||
    p.tags.some(t => t.includes(q))
  );
}

function getProductsByPriceRange(min, max) {
  return products.filter(p => p.price >= min && p.price <= max);
}

function getFeaturedProducts(limit) {
  return products.slice(0, limit || 6);
}

function getWomenProducts() {
  return products.filter(p => p.category === 'Women');
}

function getMenProducts() {
  return products.filter(p => p.category === 'Men');
}

function getBeautyProducts() {
  return products.filter(p => p.category === 'Beauty');
}

function getAllProducts() {
  return products;
}

function sortProducts(productList, sortBy) {
  const list = [...productList];
  if (sortBy === 'price-low') return list.sort((a, b) => a.price - b.price);
  if (sortBy === 'price-high') return list.sort((a, b) => b.price - a.price);
  if (sortBy === 'rating') return list.sort((a, b) => b.rating - a.rating);
  if (sortBy === 'reviews') return list.sort((a, b) => b.reviews - a.reviews);
  return list;
}

