// ============================================================
// HELPER FUNCTIONS
// ============================================================
function getProductsByCategory(cat) {
  return PRODUCTS.filter(p => p.category === cat);
}
function getProductsBySubcategory(cat, subcat) {
  return PRODUCTS.filter(p => p.category === cat && p.subcategory === subcat);
}
function getFeaturedProducts() {
  return PRODUCTS.filter(p => p.featured);
}
function getBestSellers() {
  return PRODUCTS.filter(p => p.featured).sort((a, b) => b.reviews - a.reviews);
}
function getProductById(id) {
  return PRODUCTS.find(p => p.id === id);
}

// ─────────────────────────────────────────────────────────
// getColorVariants:
// Expands each color of a product into its own "virtual card"
// Used for trending/related sections to show each color separately
// ─────────────────────────────────────────────────────────
function getColorVariants(product) {
  if (!product.colors || product.colors.length === 0) return [product];
  return product.colors.map((color, index) => ({
    ...product,
    // Give each variant a unique id so links/cards work independently
    id: `${product.id}--${index}`,
    _baseId: product.id,
    _colorIndex: index,
    // Override image and affiliate link with this color's values
    image: color.image,
    affiliateLink: color.affiliateLink,
    // Store active color name for display
    _activeColor: color.name,
    _activeHex: color.hex
  }));
}

// Returns all color variants of all featured products (for trending/homepage)
function getFeaturedColorVariants() {
  const featured = getFeaturedProducts();
  return featured.flatMap(p => getColorVariants(p));
}

// Returns color variants of related products (same category, different base id)
function getRelatedColorVariants(id, limit = 6) {
  const baseId = id.includes('--') ? id.split('--')[0] : id;
  const product = getProductById(baseId);
  if (!product) return [];
  const related = PRODUCTS.filter(p => p.category === product.category && p.id !== baseId);
  return related.flatMap(p => getColorVariants(p)).slice(0, limit);
}

function getRelatedProducts(id, limit = 3) {
  const product = getProductById(id);
  if (!product) return [];
  return PRODUCTS.filter(p => p.category === product.category && p.id !== id).slice(0, limit);
}
function getSubcategories(cat) {
  return SUBCATEGORIES[cat] || [];
}
